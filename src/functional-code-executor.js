import { code } from './ai.js';
import { registerArtifact } from './artifacts.js';
import { registerExecutor, grantExecutor } from './executor-registry.js';

const REQUIRED = ['www/index.html', 'www/app.js', 'www/styles.css', 'package.json', 'capacitor.config.json', 'README.md'];
const BAD_MARKERS = ['This application was generated by MAULI 2.0 AI Company.', 'Platform Support', 'Generated App', 'Main Application Logic'];

function text(v) { return v == null ? '' : typeof v === 'object' ? JSON.stringify(v) : String(v); }
function filesOf(value) {
  const out = [];
  for (const f of Array.isArray(value) ? value : []) {
    if (!f || typeof f.path !== 'string' || typeof f.content !== 'string') continue;
    const path = f.path.replace(/^\/+/, '').replace(/\.\.(?:[\\/])/g, '').replace(/\\/g, '/');
    if (!path || path.startsWith('android/') || path.startsWith('node_modules/')) continue;
    out.push({ path, content: f.content });
  }
  return [...new Map(out.map(f => [f.path, f])).values()];
}
function parseModel(raw) {
  if (raw && typeof raw === 'object') return raw;
  let s = text(raw).trim().replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/i, '');
  try { return JSON.parse(s); } catch {}
  const a = s.indexOf('{'), b = s.lastIndexOf('}');
  if (a >= 0 && b > a) { try { return JSON.parse(s.slice(a, b + 1)); } catch {} }
  return null;
}
function invalid(files) {
  const paths = new Set(files.map(f => f.path));
  if (REQUIRED.some(p => !paths.has(p))) return true;
  const html = files.find(f => f.path === 'www/index.html')?.content || '';
  const js = files.find(f => f.path === 'www/app.js')?.content || '';
  const css = files.find(f => f.path === 'www/styles.css')?.content || '';
  return BAD_MARKERS.some(m => html.includes(m) || js.includes(m)) || js.trim().length < 160 || css.trim().length < 40 || !/(addEventListener|onclick|function\s)/.test(js);
}

async function generateFunctionalArtifact({ task, env, agentId }) {
  // executeTaskLifecycle passes runtime bindings inside context.env. Accept both
  // forms so the executor cannot silently lose the Cloudflare AI binding.
  const runtimeEnv = env?.env?.AI ? env.env : env;
  const objective = text(task.description || task.title || 'Build a software application');
  const acceptance = Array.isArray(task.acceptance) ? task.acceptance : [];
  const system = [
    'You are MAULI 2.0 Functional Application Engineer.',
    'Generate the ACTUAL runnable product requested by the task. Never generate a mockup, placeholder, requirements checklist, brochure, or demo shell.',
    'Return ONLY one valid JSON object with keys summary, files, tests, notes.',
    'files must contain complete source code for every required file. The application MUST implement the requested features, not merely describe them.',
    'Use plain HTML/CSS/JavaScript where practical and make it runnable offline. www/index.html is the entry point and www/app.js contains real interactions.',
    'Create UI controls for the requested features and implement their behavior. Persist appropriate local state when useful.',
    'Do not use [object Object] or claim completion without implementation.',
    'For security-related requests, implement defensive functionality only; do not implement password cracking, credential theft, unauthorized access, or exploitation.',
    'Required files: ' + REQUIRED.join(', '),
    'Task: ' + objective,
    'Acceptance criteria: ' + JSON.stringify(acceptance)
  ].join('\n');

  let parsed = null;
  let lastError = '';
  for (let attempt = 0; attempt < 2 && !parsed; attempt++) {
    try {
      if (!runtimeEnv?.AI?.run) throw new Error('Cloudflare AI binding is not configured for functional code generation');
      const prompt = attempt === 0 ? objective : objective + '\nPrevious generation was invalid. Regenerate the COMPLETE application now. Output JSON only and include all required source files.';
      parsed = parseModel(await code(runtimeEnv, [{ role: 'system', content: system }, { role: 'user', content: prompt }], { maxTokens: 5000 }));
      if (!parsed || invalid(filesOf(parsed.files))) parsed = null;
    } catch (e) { lastError = text(e); parsed = null; }
  }

  const files = filesOf(parsed?.files);
  if (invalid(files)) {
    throw new Error('Functional code generation failed: MAULI refused to deliver a placeholder or incomplete application.' + (lastError ? ` ${lastError}` : ''));
  }

  const tests = Array.isArray(parsed.tests) ? parsed.tests.map(text).filter(Boolean).slice(0, 20) : [];
  const notes = Array.isArray(parsed.notes) ? parsed.notes.map(text).filter(Boolean).slice(0, 20) : [];
  const artifact = registerArtifact({
    projectId: task.projectId, taskId: task.id, agentId, type: 'code-workspace',
    content: { summary: text(parsed.summary || `Functional application generated for ${objective}`), files, tests, notes },
    metadata: { generatedBy: 'functional-code-executor', functional: true, placeholderFallback: false, fileCount: files.length }
  });
  return { type: 'code', artifactId: artifact.id, summary: artifact.content.summary, files, tests, notes, acceptance };
}

registerExecutor('internal.code', generateFunctionalArtifact, {
  description: 'Generates and gates real functional Web + Android + Desktop source projects',
  risk: 'low', scope: 'internal', capabilities: ['coding', 'software-development']
});
grantExecutor('internal.code', 'internal');
