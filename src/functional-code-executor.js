/**
 * Generate the app ONE FILE PER REQUEST, then repair it against the fidelity gate.
 *
 * The single-request path needed every file to survive one completion. Measured against the
 * live Groq provider that failed for anything larger than a toy app: the completion was cut
 * before the JSON closed, so the executor had nothing usable and quietly fell back to a
 * template. Asking for one file at a time cannot truncate the others, and each answer is
 * plain source rather than a JSON envelope, so it is far easier to parse.
 *
 * After the files are assembled, the SAME static gate the QA pipeline enforces runs eagerly.
 * When it fails, each behaviour file is asked for again with the diagnosis and the OTHER
 * files' current source as context, so the HTML's `onclick="add()"` and the JS's
 * `function add(){}` cannot drift apart. Bounded by PER_FILE_REPAIR_ROUNDS.
 */
async function generateFileByFile({ runtimeEnv, systemPrompt, objective, acceptance, task }) {
  const plan = behaviourPlan(task);
  const collected = new Map();
  const missing = [];
  const system = perFileSystemPrompt(systemPrompt);
  const analyse = (files) => analyzeGeneratedApp(files, { objective, requirements: task?.requirements ?? [] });
  // package.json and README.md are always synthesised, never requested: they are not product
  // code, and the model answered them inconsistently (empty {} manifests included).
  const assemble = () => ensureReadme(ensurePackageJson([...collected.values()], objective), objective);

  async function request(path, spec, { context = '', repair = '' } = {}) {
    const ask = 'Write ' + path + ' for this product.\n\n' + spec +
      (context ? '\n\nThe app\u2019s other files are:\n' + context : '') +
      (repair ? '\n\nYour previous version of this file failed the functional review. Fix EXACTLY these problems:\n' + repair : '') +
      '\n\nProduct: ' + objective +
      '\nAcceptance criteria: ' + JSON.stringify(acceptance) +
      '\n\nOutput ONLY the raw contents of ' + path + '. No markdown fence, no explanation, no JSON wrapper, no other file.';
    try {
      const raw = await withTimeout(code(runtimeEnv, [
        { role: 'system', content: system },
        { role: 'user', content: ask },
      ], { maxTokens: PER_FILE_MAX_TOKENS }), AI_ATTEMPT_TIMEOUT_MS);
      const content = unwrapFileContent(path, raw).trim();
      // A file that came back empty, or as prose/envelope instead of the file, is not a
      // file. Refusing it here is what keeps a half-written app from being registered as
      // the product.
      return looksLikeFileSource(path, content) ? content : null;
    } catch (e) { return null; }
  }

  for (const [path, spec] of plan) {
    const content = await request(path, spec);
    if (content) collected.set(path, { path, content });
    else missing.push(path);
  }
  if (!collected.size) return { files: null, error: `per-file generation produced nothing (${missing.join('; ') || 'no files requested'})` };

  let files = assemble();
  let quality = analyse(files);
  let repaired = 0;

  // Detect → Diagnose → Fix/Rebuild → Retest. A per-file app can still arrive as a static
  // shell (HTML renders no controls, JS binds none); rewriting the behaviour files with the
  // gate's findings is the only thing that turns it into a working product.
  for (let round = 0; round < PER_FILE_REPAIR_ROUNDS && !quality.passed; round++) {
    const codes = quality.violations.filter(v => v.severity === 'critical').map(v => v.code);
    if (!codes.length) break;
    const repair = repairInstruction(codes);
    let changed = false;
    for (const [path, spec] of plan) {
      const context = [...collected.values()].filter(f => f.path !== path)
        .map(f => '// file: ' + f.path + '\n' + f.content).join('\n\n');
      const content = await request(path, spec, { context, repair });
      if (content) { collected.set(path, { path, content }); changed = true; }
    }
    if (!changed) break;
    repaired += 1;
    files = assemble();
    quality = analyse(files);
  }

  // The same structural bar the single-request path was held to, so a per-file app that is
  // missing its HTML is refused exactly as a truncated one was.
  if (invalid(files, task)) return { files: null, error: `per-file output is incomplete (${missing.join('; ') || 'missing required files'})` };
  return { files, quality, missing, repaired, strategy: 'file-by-file' };
}

/**
 * Generate the app, ONE FILE PER REQUEST.
 *
 * This used to try a single whole-app completion first and fall back to per-file. Measured
 * live against Groq, the single request never produced a parseable app: one completion asked
 * to emit five files as escaped JSON came back truncated or malformed every time, so every
 * generation paid for doomed attempts (up to two, 40s each) before the per-file path did the
 * work. Raw per-file source is what the model can actually emit, so it is now the one path.
 * See generateFileByFile() for the fidelity repair that closes the second half of the problem.
 */
async function generateWithRepair({ runtimeEnv, systemPrompt, objective, acceptance, task }) {
  return generateFileByFile({ runtimeEnv, systemPrompt, objective, acceptance, task })
    .catch(error => ({ files: null, error: text(error) }));
}

function withTimeout(promise, ms) {
  let timer;
  const timeout = new Promise((_, reject) => {
    timer = setTimeout(() => reject(new Error('AI generation timeout')), ms);
  });
  return Promise.race([promise, timeout]).finally(() => clearTimeout(timer));
}

