import { id, now } from './core.js';
import { store } from './store.js';
import { registerArtifact } from './artifacts.js';

/**
 * Documentation Generator — automatically generates documentation
 * for projects, system changes, and API references.
 */

/**
 * Generate full project documentation
 */
export function generateProjectDocs(projectId) {
  const project = store.get('projects', projectId);
  if (!project) return { error: 'Project not found' };

  const tasks = store.list('tasks').filter(t => t.projectId === projectId);
  const artifacts = store.list('artifacts').filter(a => a.projectId === projectId);
  const edits = store.list('file_edits').filter(e => e.projectId === projectId);
  const activities = store.list('activities').filter(a => a.projectId === projectId);

  const completed = tasks.filter(t => t.state === 'completed');
  const failed = tasks.filter(t => t.state === 'failed');

  // Generate README
  const readme = generateReadme(project, tasks, artifacts, edits);

  // Generate CHANGELOG
  const changelog = generateChangelog(project, edits, activities);

  // Generate API docs
  const apiDocs = generateApiDocs(project, artifacts);

  // Generate architecture doc
  const architecture = generateArchitecture(project, tasks, artifacts);

  // Store as artifact
  const docArtifact = registerArtifact({
    projectId,
    taskId: null,
    agentId: null,
    type: 'code-workspace',
    content: {
      summary: `Documentation for ${project.name}`,
      files: [
        { path: 'docs/README.md', content: readme },
        { path: 'docs/CHANGELOG.md', content: changelog },
        { path: 'docs/API.md', content: apiDocs },
        { path: 'docs/ARCHITECTURE.md', content: architecture }
      ],
      tests: [],
      notes: ['Auto-generated documentation']
    },
    metadata: { generatedBy: 'docs-generator', docType: 'project-documentation' }
  });

  return docArtifact;
}

/**
 * Generate README.md
 */
function generateReadme(project, tasks, artifacts, edits) {
  const completed = tasks.filter(t => t.state === 'completed').length;
  const total = tasks.length;

  let md = `# ${project.name || project.objective}\n\n`;
  md += `> Generated by MAULI 2.0 AI Company\n\n`;
  md += `## Overview\n\n`;
  md += `${project.objective || 'No description available.'}\n\n`;
  md += `## Status\n\n`;
  md += `| Metric | Value |\n|--------|-------|\n`;
  md += `| Status | ${project.state} |\n`;
  md += `| Tasks | ${completed}/${total} completed |\n`;
  md += `| Artifacts | ${artifacts.length} |\n`;
  md += `| Edits | ${edits.length} |\n`;
  md += `| Created | ${project.createdAt || 'Unknown'} |\n`;
  md += `| Updated | ${project.updatedAt || 'Unknown'} |\n\n`;

  if (project.requirements && project.requirements.length) {
    md += `## Requirements\n\n`;
    for (const req of project.requirements) {
      md += `- ${req}\n`;
    }
    md += `\n`;
  }

  md += `## Tasks\n\n`;
  for (const task of tasks) {
    const icon = task.state === 'completed' ? '✅' : task.state === 'failed' ? '❌' : '⏳';
    md += `${icon} **${task.title}** [${task.state}]\n`;
    if (task.description) md += `   ${task.description}\n`;
    md += `\n`;
  }

  if (artifacts.length) {
    md += `## Artifacts\n\n`;
    for (const art of artifacts) {
      md += `- **${art.type}** (${art.id})\n`;
    }
    md += `\n`;
  }

  md += `## Built with\n\n`;
  md += `- **MAULI 2.0** — Autonomous AI Company Platform\n`;
  md += `- **18 AI Agents** — Research, Planning, Frontend, Backend, Database, Security, QA, DevOps, Mobile, Desktop, AI/ML, Data, Creative, API, PDF, Native\n`;
  md += `- **5 Executors** — Plan, Code, Verify, PDF, Native\n`;
  md += `- **6 Build Workflows** — APK, IPA, EXE, DMG, AppImage, Deploy\n\n`;

  md += `---\n*Auto-generated by MAULI 2.0 Documentation Generator*\n`;

  return md;
}

/**
 * Generate CHANGELOG.md
 */
function generateChangelog(project, edits, activities) {
  let md = `# Changelog\n\n`;
  md += `All notable changes to this project.\n\n`;

  // Group edits by date
  const editsByDate = {};
  for (const edit of edits) {
    const date = String(edit.timestamp).split('T')[0] || 'Unknown';
    if (!editsByDate[date]) editsByDate[date] = [];
    editsByDate[date].push(edit);
  }

  for (const [date, dateEdits] of Object.entries(editsByDate).sort((a, b) => b[0].localeCompare(a[0]))) {
    md += `## ${date}\n\n`;
    for (const edit of dateEdits) {
      const icon = edit.operation === 'create' ? '🆕' : edit.operation === 'delete' ? '🗑️' : '✏️';
      md += `- ${icon} **${edit.operation}** \`${edit.filePath}\` — ${edit.description}\n`;
    }
    md += `\n`;
  }

  // Activities
  if (activities.length) {
    md += `## Activity Log\n\n`;
    for (const act of activities.slice(0, 20)) {
      const icon = act.type === 'completed' ? '✅' : act.type === 'failed' ? '❌' : '🔄';
      md += `- ${icon} ${act.description} (${act.timestamp})\n`;
    }
    md += `\n`;
  }

  md += `---\n*Auto-generated by MAULI 2.0 Documentation Generator*\n`;

  return md;
}

