// MAULI 2.0 — spec-driven FULL-STACK generation.
//
// Until now MAULI could only produce a browser page: forms, handlers and localStorage.
// That is a legitimate product for a founder who asked for an offline note pad, and it is
// a fake product for anyone who asked for accounts, shared data or live updates — because
// there was nothing behind the page to talk to.
//
// This generator is deliberately NOT a template library. It is a compiler: it reads the
// founder's extracted specification and emits the architecture that specification selected
// (src/architecture.js) — a real Worker entry point with real D1 SQL, real session
// enforcement, real WebSocket broadcast and a frontend that calls those endpoints. The
// founder's domain nouns become the entity and its columns, so the delivered product is
// the product that was requested rather than whichever sample happened to be nearest.
//
// "Generate less, implement correctly": one deterministic, verified shape beats a page of
// code the runtime then has to prove does nothing.

const ENTITY = 'record';

function pascal(text) {
  return String(text).split(/[^A-Za-z0-9]+/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join('') || 'Journey';
}

function singular(word) {
  const w = String(word || 'record').toLowerCase();
  if (/(ies)$/.test(w)) return w.slice(0, -3) + 'y';
  if (/(ses|xes|zes|ches|shes)$/.test(w)) return w.slice(0, -2);
  if (/s$/.test(w) && !/ss$/.test(w)) return w.slice(0, -1);
  return w;
}

function camel(text) {
  const p = pascal(text);
  return p[0].toLowerCase() + p.slice(1);
}

function titleCase(text) {
  return String(text).split(/\s+/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join(' ');
}

/**
 * Did the founder ask for something that happens AT A TIME — a schedule, a due date, a
 * reminder? Read from the features the specification derived, not from the objective's
 * wording, so it stays in step with the requirement the founder can actually contest.
 */
/**
 * Quote a SQL identifier. A founder's product can be called "order", "group" or "user", and
 * every one of those is a SQL keyword: an unquoted CREATE TABLE order is a syntax error that
 * turns every request into a 500, which is exactly what a real deployment reported.
 */
function quoteSql(identifier) {
  return '"' + String(identifier ?? '').replace(/"/g, '""') + '"';
}

function wantsScheduling(spec) {
  return (spec?.features ?? []).some((f) => ['reminder', 'notification'].includes(f?.key));
}

/**
 * Pluralise a record resource the way English does.
 *
 * `/api/entrys` is not a resource, it is a typo that a founder sees in the URL bar and a
 * test cannot guess. `-y` becomes `-ies`; the sibilant endings take `-es`.
 */
function plural(noun) {
  const n = String(noun ?? '');
  if (!n) return n;
  if (/(?:s|x|z|ch|sh)$/i.test(n)) return `${n}es`;
  if (/[^aeiou]y$/i.test(n)) return `${n.slice(0, -1)}ies`;
  if (/[^f]fe$/i.test(n)) return `${n.slice(0, -2)}ves`;
  return `${n}s`;
}

/** The domain noun the founder actually used, used for the entity and its labels. */
export function domainEntity(spec) {
  const words = (spec?.domainWords ?? []).filter((w) => w.length > 2);
  const typeMap = {
    ecommerce: 'order', crm: 'lead', booking: 'booking', inventory: 'item', finance: 'expense',
    health: 'entry', education: 'result', productivity: 'task', dashboard: 'report', automation: 'run'
  };
  if (spec?.productType && typeMap[spec.productType]) return typeMap[spec.productType];
  return singular(words[0] ?? 'record');
}

export function entityLabel(spec) {
  const e = domainEntity(spec);
  return titleCase(e);
}

