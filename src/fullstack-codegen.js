function wranglerJsonc({ table, realtime, backend = true }) {
  // A browser-only product ships no Worker, so it must declare no `main`: wrangler loads the
  // declared entry point before anything else and refuses to deploy a config whose main is
  // a file that was never generated. The product would have been a website nobody could host.
  return `{
  "name": "generated-${table}-api",${backend ? `
  "main": "worker/index.js",` : ''}
  "workers_dev": ${backend ? 'true' : 'false'},
  "compatibility_date": "2026-08-19",
  "compatibility_flags": ["nodejs_compat"],
  "assets": {
    "directory": "./www"${backend ? `,
    "binding": "ASSETS"` : ''}
  },
  "d1_databases": ${backend ? `[
    {
      "binding": "DB",
      "database_name": "generated_${table}",
      "database_id": "replace-with-your-d1-database-id",
      "migrations_dir": "migrations"
    }
  ]` : '[]'}${realtime ? `,
  "durable_objects": {
    "bindings": [{ "name": "LIVE", "class_name": "LiveConnections" }]
  },
  "exports": {
    "LiveConnections": { "type": "durable-object", "storage": "sqlite" }
  }` : ''}
}
`;
}

