/**
 * A stable accent hue per product, so two generated products never look like the same
 * template with a different noun in it.
 */
function accentFor(label) {
  let h = 0;
  for (const ch of String(label ?? '')) h = (h * 31 + ch.codePointAt(0)) % 360;
  return h;
}

