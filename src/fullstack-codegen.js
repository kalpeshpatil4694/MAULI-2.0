/**
 * Generate the full product the specification asked for.
 * @returns {{files:Array<{path:string,content:string}>, summary:string, table:string,
 *   label:string, architecture:object}}
 */
export function generateFullStackApp(spec, architecture, { objective = '' } = {}) {
  const table = domainEntity(spec);
  const entity = camel(table);
  const label = entityLabel(spec);
  // A browser-only product keeps its records on the device, so the only place its domain
  // can be named is the app itself. The catalogue's generic entity ("entry") gave a founder
  // a medicine tracker whose every identifier said "entry" — the product never said what it
  // was for. The founder's own noun is used instead whenever there is one.
  const localNoun = architecture.backend
    ? null
    : (spec.inferredFromDomain ?? (spec.domainWords ?? []).find((w) => typeof w === 'string' && w.length > 3) ?? null);
  const frontTable = localNoun ?? table;
  const frontEntity = camel(frontTable);
  const frontLabel = localNoun ? frontEntity : label;
  // A browser-only architecture ships no server. Emitting a Worker and a D1 migration for a
  // product that promised to keep its records on the device gave the founder a product whose
  // own documentation contradicted its own code.
  const files = [
    { path: 'www/index.html', content: frontendHtml({ spec, architecture, table: frontTable, entity: frontEntity, label: frontLabel, page: 'dashboard' }) },
    { path: 'www/reports.html', content: frontendHtml({ spec, architecture, table: frontTable, entity: frontEntity, label: frontLabel, page: 'reports' }) },
    { path: 'www/settings.html', content: frontendHtml({ spec, architecture, table: frontTable, entity: frontEntity, label: frontLabel, page: 'settings' }) },
    { path: 'www/app.js', content: frontendJs({ spec, architecture, table: frontTable, entity: frontEntity, label: frontLabel }) },
    { path: 'www/styles.css', content: frontendCss({ label: frontLabel, hue: accentFor(frontLabel) }) },
    ...(architecture.backend
      ? [
        { path: 'worker/index.js', content: workerSource({ spec, architecture, table, entity, label }) },
        { path: 'migrations/0001_init.sql', content: schemaSql({ table, auth: architecture.auth, realtime: architecture.realtime, due: wantsScheduling(spec) }) },
        { path: 'wrangler.jsonc', content: wranglerJsonc({ table, realtime: architecture.realtime }) }
      ]
      : [{ path: 'wrangler.jsonc', content: wranglerJsonc({ table: frontTable, realtime: false, backend: false }) }]),
    {
      path: 'package.json',
      content: JSON.stringify({
        name: `generated-${table}`,
        version: '1.0.0',
        private: true,
        type: 'module',
        scripts: {
          dev: 'wrangler dev',
          deploy: 'wrangler deploy',
          'db:migrate:local': `wrangler d1 migrations apply generated_${table} --local`,
          test: 'node --test'
        }
      }, null, 2)
    },
    { path: 'README.md', content: readme({ spec, architecture, label, table }) }
  ];
  return {
    files,
    table,
    api: `/api/${plural(table)}`,
    label,
    architecture,
    summary: `${label} — ${architecture.label}. ${architecture.backend ? 'Worker API over D1' : 'local device store'}${architecture.auth ? ', session-protected' : ''}${architecture.realtime ? ', live updates over WebSocket' : ''}.`,
    tests: [
      'Create a record through the UI and see it in the list',
      'Reload the page and confirm the record is still there',
      ...(architecture.auth ? ['Register, log out, and confirm a protected read is refused while signed out'] : []),
      ...(architecture.realtime ? ['Open two tabs, add a record in one, and see it appear in the other'] : [])
    ],
    notes: [`Generated from ${spec.requirements?.length ?? 0} extracted requirements via ${spec.productType ?? 'generic'} specification.`]
  };
}

export default generateFullStackApp;
