function schemaSql({ table, auth, realtime, due = false }) {
  const parts = [];
  parts.push(`-- Generated by MAULI 2.0 from the founder's requirement specification.
-- Every table below backs a requirement in the delivered requirement matrix.
CREATE TABLE IF NOT EXISTS ${quoteSql(table)} (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  title TEXT NOT NULL,
  detail TEXT,
  amount REAL DEFAULT 0,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  owner_email TEXT${due ? ',\n  due TEXT' : ''}
);`);
  if (auth) {
    parts.push(`CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  email TEXT NOT NULL UNIQUE,
  name TEXT,
  password_hash TEXT NOT NULL,
  salt TEXT NOT NULL,
  created_at TEXT NOT NULL
);`);
    parts.push(`CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY,
  user_email TEXT NOT NULL,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL
);`);
  }
  if (realtime) {
    parts.push(`CREATE TABLE IF NOT EXISTS rooms (
  id TEXT PRIMARY KEY,
  client_count INTEGER DEFAULT 0
);`);
  }
  return parts.join('\n\n');
}

